/**
 * Generates content-manifest.json — the question counts shown on the practice
 * hubs.
 *
 * Without it, practice.html has to fetch all 11 topic quiz files (and the
 * mixed-practice page another 3) purely to count questions. This collapses
 * that into a single cached request.
 *
 * Run after changing any quiz data:   npm run build:manifest
 * (`npm run build` does it for you.)
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

async function countQuestions(file) {
  const data = JSON.parse(await readFile(file, "utf8"));
  return Array.isArray(data.questions) ? data.questions.length : 0;
}

async function countDir(dir) {
  const out = {};
  const names = (await readdir(dir)).filter((n) => n.endsWith(".json")).sort();
  for (const name of names) {
    out[path.basename(name, ".json")] = await countQuestions(path.join(dir, name));
  }
  return out;
}

const topics = await countDir(path.join(root, "level1", "quiz"));
const mixed = await countDir(path.join(root, "level2", "data"));

const manifest = {
  _note: "Generated by scripts/build-manifest.mjs — do not edit by hand.",
  generated: new Date().toISOString(),
  topics,
  mixed
};

await writeFile(
  path.join(root, "content-manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n",
  "utf8"
);

const total =
  Object.values(topics).reduce((a, b) => a + b, 0) +
  Object.values(mixed).reduce((a, b) => a + b, 0);

console.log(
  `content-manifest.json written — ${Object.keys(topics).length} topics, ` +
    `${Object.keys(mixed).length} mixed sets, ${total} questions total`
);
